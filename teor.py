# Что такое парсинг?

'''**Парсинг** (от англ. *parsing*, что переводится как "разбор") — это процесс 
извлечения и анализа данных из какого-либо источника, такого как веб-страницы, 
файлы или API. Основная цель парсинга — автоматическое получение нужной информации
и преобразование её в удобный формат для обработки.

'''

# Примеры использования парсинга:
# 1. **Веб-парсинг (Web Scraping):**
#    - Извлечение текстов, изображений, таблиц или других данных с веб-сайтов.
#    - Пример: Сбор цен товаров из интернет-магазинов для анализа.

# 2. **Парсинг файлов:**
#    - Чтение структурированных файлов (например, JSON, XML, CSV) и извлечение данных для работы.
#    - Пример: Анализ логов сервера или обработка банковских выписок.

# 3. **Парсинг API:**
#    - Получение и обработка данных, предоставляемых через API.
#    - Пример: Использование API для получения курса валют или прогноза погоды.

# 4. **Парсинг HTML-кода:**
#    - Анализ структуры HTML-документов для извлечения нужной информации.
#    - Пример: Сбор заголовков статей с новостного портала.



# Как это работает?
'''
1. **Источники данных:** Данные могут быть получены из различных источников — веб-страниц, файлов, API.  
2. **Обработка структуры:** Анализируется структура данных, например, HTML-документ с использованием тегов.  
3. **Извлечение информации:** С помощью специальных инструментов или библиотек данные извлекаются и преобразуются.  
4. **Сохранение:** Результат сохраняется в удобном формате: файл, база данных или просто отображается в консоли.

'''

# Основные библиотеки для парсинга в Python:
'''
1. **`requests`:** Для отправки HTTP-запросов к веб-страницам или API.
2. **`BeautifulSoup` (из пакета `bs4`):** Для обработки и анализа HTML и XML.
3. **`lxml`:** Для работы с XML и HTML-документами (быстрый и мощный инструмент).
4. **`json`:** Для обработки JSON-данных.
5. **`re`:** Для поиска данных с использованием регулярных выражений.
'''


# пример:
# **Задача:** Получить заголовок веб-страницы.  

import requests
from bs4 import BeautifulSoup

# URL страницы
url = 'https://www.example.com'

# Отправляем запрос
response = requests.get(url)

# Разбираем HTML-код
soup = BeautifulSoup(response.text, 'html.parser')

# Извлекаем заголовок
title = soup.title.string

print(f"Заголовок страницы: {title}")


# # Преимущества парсинга:
# - Автоматизация сбора данных.
# - Быстрая обработка больших объёмов информации.
# - Возможность интеграции с другими приложениями.

# Недостатки и риски:
# - **Юридические ограничения:** Некоторые сайты запрещают парсинг их данных (проверяйте "robots.txt").  
# - **Изменения структуры данных:** Если структура сайта изменится, парсер может перестать работать.  
# - **Блокировка:** Чрезмерное количество запросов может привести к блокировке IP-адреса.

